/**
 * Persistence port for organizational-unit administration (T178, ADR-004,
 * data-model.md §4). `core/organizations/application` depends on this
 * abstract class — never on `PrismaService` directly (ADR-011).
 * `core/organizations/infrastructure/prisma-org-unit-admin.repository.ts`
 * is the only implementation, wired in `organizations.module.ts`.
 *
 * Distinct from `OrgUnitDirectoryPort` (T096a), which backs the
 * SCOPE-FILTERED, non-administrative `GET /org-units` read: administrative
 * reads and writes here are never scope-filtered (`GET /admin/org-units`
 * "returns every unit regardless of the caller's scope", per
 * `contracts/admin.openapi.yaml`).
 */
import type { OrgUnitStatus } from '@prisma/client';

/** Mirrors `contracts/admin.openapi.yaml`'s `OrgUnitNode` schema. */
export interface OrgUnitAdminRecord {
  readonly id: string;
  readonly code: string;
  readonly name: string;
  readonly parentId: string | undefined;
  readonly path: string;
  readonly depth: number;
  readonly status: OrgUnitStatus;
  readonly childCount: number;
}

/** The minimal shape `domain/org-unit-path.ts`'s pure functions
 * (`computeChildPath`, `canReparent`, `recomputeSubtreePaths`) operate on. */
export interface OrgUnitPathInfoRecord {
  readonly id: string;
  readonly path: string;
  readonly depth: number;
}

export interface CreateOrgUnitRow {
  /** Generated by the caller (`OrgUnitAdminService`) BEFORE the row is
   * inserted — see that service's file header for why the materialized
   * path requires knowing the id in advance. */
  readonly id: string;
  readonly code: string;
  readonly name: string;
  readonly parentId: string | undefined;
  readonly path: string;
  readonly depth: number;
}

export interface UpdateOrgUnitFields {
  readonly code?: string;
  readonly name?: string;
}

/** The pre-update `code`/`name` values, for the audit diff. */
export interface PreviousOrgUnitFields {
  readonly code: string;
  readonly name: string;
}

export interface ReparentDescendantUpdate {
  readonly id: string;
  readonly path: string;
  readonly depth: number;
}

export interface ApplyReparentInput {
  readonly unitId: string;
  /** `undefined` when the unit becomes a root. */
  readonly parentId: string | undefined;
  readonly path: string;
  readonly depth: number;
  readonly descendants: readonly ReparentDescendantUpdate[];
}

export abstract class OrgUnitAdminRepositoryPort {
  /** `GET /admin/org-units` — the full tree, unscoped, ordered by
   * materialized path. */
  abstract listAll(status: OrgUnitStatus | undefined): Promise<readonly OrgUnitAdminRecord[]>;

  abstract findById(id: string): Promise<OrgUnitAdminRecord | undefined>;

  /** For the `code` uniqueness pre-check (409) on create/update.
   * `excludeUnitId` lets `update` check "does another unit already use
   * this code" without matching the unit being renamed to its own current
   * code. */
  abstract findByCode(
    code: string,
    excludeUnitId?: string,
  ): Promise<{ readonly id: string } | undefined>;

  /** For `domain/org-unit-path.ts`'s pure path functions — the unit's own
   * current path/depth, or `undefined` if it does not exist. */
  abstract findPathInfoById(id: string): Promise<OrgUnitPathInfoRecord | undefined>;

  /** Every unit whose path is a STRICT descendant of `path` (excludes the
   * unit itself) — the input `recomputeSubtreePaths` needs to repath a
   * moved unit's whole subtree. */
  abstract findStrictDescendantsPathInfo(path: string): Promise<readonly OrgUnitPathInfoRecord[]>;

  /** True when at least one unit strictly under `path` (excluding the unit
   * itself) has `status: ACTIVE` — `PUT .../status`'s "an active
   * descendant unit prevents deactivation" rule. */
  abstract hasActiveDescendant(path: string): Promise<boolean>;

  abstract create(input: CreateOrgUnitRow): Promise<OrgUnitAdminRecord>;

  /** Updates only `code`/`name` — path/depth/parentId changes go through
   * `applyReparent`, kept as a distinct operation because it also touches
   * every descendant row (data-model.md §4). Returns the pre-update values
   * for the audit diff, or `undefined` if the unit does not exist. */
  abstract updateFields(
    id: string,
    patch: UpdateOrgUnitFields,
  ): Promise<PreviousOrgUnitFields | undefined>;

  /** Applies a reparent: updates the moved unit's own
   * `parentId`/`path`/`depth` and every descendant's `path`/`depth`, in
   * one call so the caller's transaction covers all of it (ADR-004: "the
   * subtree updated ... in the same transaction"). */
  abstract applyReparent(input: ApplyReparentInput): Promise<void>;

  /** Returns the previous status, or `undefined` if the unit does not
   * exist (404). */
  abstract setStatus(id: string, status: OrgUnitStatus): Promise<OrgUnitStatus | undefined>;
}
