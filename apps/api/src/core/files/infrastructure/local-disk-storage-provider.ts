/**
 * T188 — `LocalDiskStorageProvider`: the only `FileStorageProvider` adapter
 * in this release (ADR-010). Writes to `ATTACHMENT_STORAGE_PATH`
 * (`AppConfigService.attachment.storagePath`) under generated,
 * content-addressed keys — this class is the ONLY place in the codebase
 * that turns a storage key into a filesystem path, which is what makes the
 * path-traversal guarantee provable in one file rather than by convention
 * scattered across callers.
 *
 * ## Content-addressing, partitioned by organizational unit (ADR-010:
 * "under content-addressed keys"; F-26 fix, research.md D-12/D-R12)
 *
 * The storage key is derived from the SHA-256 of the content itself, under
 * a prefix that partitions by the organizational unit the caller resolved
 * (`org/<orgUnitId>/sha256/<aa>/<bb>/<64-hex-digest>`, or
 * `unscoped/sha256/<aa>/<bb>/<64-hex-digest>` for a parent type with no
 * organizational scope of its own — its OWN bucket, never the legacy
 * prefix, never a scoped one) — never from `Attachment.fileName`, which
 * `UploadService` never even passes to this class. Three independent
 * consequences:
 *
 *   1. **Path traversal is structurally impossible, not merely
 *      validated.** A user-supplied file name (however hostile —
 *      `../../etc/passwd`, absolute paths, embedded NUL) never reaches
 *      `resolveStoragePath` at all; it travels only as `Attachment.fileName`
 *      metadata, read back solely to build a `Content-Disposition` header
 *      (`AttachmentController`, T190). `resolveStoragePath`'s own
 *      containment assertion below is therefore defense in depth against a
 *      FUTURE bug (a `storageKey` corrupted or mistakenly hand-built), not
 *      the primary defense — the primary defense is that this class never
 *      accepts an untrusted string as a path component in the first place.
 *      `organizationalUnitId` reaches this class the same way `storageKey`
 *      does: server-resolved (`UploadService`'s `parentAccess
 *      .organizationalUnitId`), never client-supplied, so the same
 *      argument applies to the new path segment.
 *   2. **Identical content uploaded twice, for the SAME organizational
 *      unit, reuses the same file** — `put` is a no-op write (`wx` flag,
 *      ignoring `EEXIST`) when the target already exists, so re-uploading
 *      byte-identical content within one unit never collides, never
 *      duplicates storage, and never throws. The SAME content uploaded for
 *      a DIFFERENT unit is a cache miss by construction (different key
 *      prefix) and is written again, deliberately — that duplication is
 *      the price of closing the cross-scope oracle F-26 measured, and this
 *      product accepts it (research.md D-12).
 *   3. **Pre-existing `sha256/...` keys (no partition prefix) keep
 *      resolving, untouched.** `get(storageKey)` reads whatever key is
 *      literally stored on the `Attachment` row — nothing here rewrites a
 *      historical key or moves a historical blob. Partitioning applies
 *      only to keys generated by NEW calls to `put` from this point
 *      forward. The residual this leaves, named rather than hidden: two
 *      subjects who can both reach the timing-measurement point for the
 *      SAME organizational unit (i.e. both hold view access to at least
 *      one entity of the relevant type in that unit) can still probe each
 *      other for content existing anywhere in that shared unit — the fix
 *      closes the CROSS-SCOPE oracle the measurement demonstrated, not a
 *      WITHIN-UNIT one. That residual does not cross a boundary this
 *      platform enforces elsewhere: this platform's authorization already
 *      scopes visibility by organizational unit, not by individual record.
 */
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { Injectable } from '@nestjs/common';

import { AppConfigService } from '../../../infrastructure/config/app-config.service';
import { FileStorageProvider, type StoredFile } from '../domain/ports/file-storage-provider.port';

import type { Readable } from 'node:stream';

@Injectable()
export class LocalDiskStorageProvider extends FileStorageProvider {
  private readonly root: string;

  constructor(appConfig: AppConfigService) {
    super();
    this.root = path.resolve(appConfig.attachment.storagePath);
  }

  async put(content: Buffer, organizationalUnitId: string | undefined): Promise<StoredFile> {
    const checksumSha256 = createHash('sha256').update(content).digest('hex');
    const relativeKey = relativeKeyFor(checksumSha256, organizationalUnitId);
    const absolutePath = this.resolveStoragePath(relativeKey);

    await mkdir(path.dirname(absolutePath), { recursive: true });
    try {
      // `wx`: create-exclusive. A pre-existing file at this path can ONLY
      // be byte-identical content (the path is a function of the SHA-256
      // of the content, so a hash collision would be required for it to
      // be anything else) — `EEXIST` is therefore treated as "already
      // stored", never as "someone else's different content is in the
      // way".
      await writeFile(absolutePath, content, { flag: 'wx' });
    } catch (error) {
      if (!isNodeErrnoException(error) || error.code !== 'EEXIST') {
        throw error;
      }
    }

    return { storageKey: relativeKey, checksumSha256, sizeBytes: content.length };
  }

  // Not `async`: opening a lazy read stream is synchronous once the safe
  // path is resolved. `Promise.resolve(...)` satisfies the port's declared
  // `Promise<Readable>` signature — a future adapter that genuinely awaits
  // (e.g. an S3 presigned-URL fetch) is free to become `async` on its own.
  get(storageKey: string): Promise<Readable> {
    const absolutePath = this.resolveStoragePath(storageKey);
    return Promise.resolve(createReadStream(absolutePath));
  }

  async delete(storageKey: string): Promise<void> {
    const absolutePath = this.resolveStoragePath(storageKey);
    await rm(absolutePath, { force: true });
  }

  /** The one place a `storageKey` becomes a filesystem path. Asserts the
   * resolved path never escapes {@link root} — see this file's header for
   * why this is defense in depth rather than the primary path-traversal
   * defense (`storageKey` is always platform-generated, never derived from
   * a caller-supplied file name). */
  private resolveStoragePath(storageKey: string): string {
    const absolutePath = path.resolve(this.root, storageKey);
    const rootWithSeparator = this.root.endsWith(path.sep) ? this.root : `${this.root}${path.sep}`;
    if (absolutePath !== this.root && !absolutePath.startsWith(rootWithSeparator)) {
      throw new Error(
        `Refusing to resolve storage key outside the storage root (root="${this.root}").`,
      );
    }
    return absolutePath;
  }
}

/** F-26 fix (research.md D-12/D-R12): the scope segment a key is
 * partitioned under. `UNSCOPED_BUCKET` is its OWN explicit, named bucket —
 * never the bare `sha256/...` prefix (that prefix is legacy, pre-partition
 * history, never a valid target for a NEW key) and never a scoped
 * caller's own `org/<id>` bucket. `organizationalUnitId` is a UUID
 * (server-resolved, never client-supplied — see this file's header), so it
 * can never collide with the literal string `unscoped`. */
const UNSCOPED_BUCKET = 'unscoped';

/** `<scope>/sha256/<first 2 hex chars>/<next 2 hex chars>/<full 64-hex
 * digest>`, where `<scope>` is `org/<organizationalUnitId>` or
 * `unscoped` — two-level hex fan-out purely to bound directory size within
 * one scope; the fan-out prefix carries no meaning beyond that. */
function relativeKeyFor(checksumSha256: string, organizationalUnitId: string | undefined): string {
  const scopeSegments =
    organizationalUnitId === undefined ? [UNSCOPED_BUCKET] : ['org', organizationalUnitId];
  return path.join(
    ...scopeSegments,
    'sha256',
    checksumSha256.slice(0, 2),
    checksumSha256.slice(2, 4),
    checksumSha256,
  );
}

function isNodeErrnoException(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && 'code' in error;
}
